import type {
  DecisionMatrix,
  Pathway,
  StudentProfile,
} from "./types";


// ============================================================
// API CONFIG
// ============================================================

const API_BASE =
  import.meta.env.VITE_API_BASE ??
  "http://localhost:8000";


// ============================================================
// BACKEND PROFILE
// ============================================================

function toBackendProfile(profile: StudentProfile) {
  return {
    name: profile.name || "Student",

    country: profile.country ?? "India",

    grade: profile.grade ?? 10,

    subjects: profile.subjects ?? [],

    marks: profile.marks ?? 0,

    budget: profile.budgetAnnual ?? 0,

    currency: profile.currency ?? "INR",

    location_preference:
      profile.locationPreference ?? "flexible",

    interests:
      profile.interests ?? [],

    countries:
      profile.preferredCountries ?? [],

    financial_aid:
      profile.financialAid ?? true,
  };
}


// ============================================================
// NORMALIZE GROQ PATHWAY
// ============================================================

function normalizePathway(raw: any): Pathway {
  let fit = 75;

  if (typeof raw?.fit === "number") {
    fit = Math.max(
      0,
      Math.min(100, raw.fit)
    );
  }

  if (typeof raw?.fit === "string") {
    const text = raw.fit.toLowerCase();

    if (text.includes("excellent")) {
      fit = 90;
    } else if (text.includes("high")) {
      fit = 85;
    } else if (text.includes("strong")) {
      fit = 82;
    } else if (text.includes("good")) {
      fit = 78;
    } else if (text.includes("moderate")) {
      fit = 70;
    } else if (text.includes("low")) {
      fit = 55;
    }
  }


  // ----------------------------------------------------------
  // Duration
  // ----------------------------------------------------------

  let durationYears = 4;

  if (
    typeof raw?.durationYears ===
    "number"
  ) {
    durationYears = raw.durationYears;
  } else if (
    typeof raw?.duration === "string"
  ) {
    const match =
      raw.duration.match(/\d+/);

    if (match) {
      durationYears =
        Number(match[0]);
    }
  }


  // ----------------------------------------------------------
  // Countries
  // ----------------------------------------------------------

  const countries =
    Array.isArray(raw?.countries)
      ? raw.countries.filter(
          (country: unknown) =>
            typeof country === "string"
        )
      : [];


  // ----------------------------------------------------------
  // Admission
  // ----------------------------------------------------------

  const admission =
    Array.isArray(raw?.admission)
      ? raw.admission
      : Array.isArray(raw?.admissions)
        ? raw.admissions
        : typeof raw?.admissions === "string"
          ? [raw.admissions]
          : [];


  // ----------------------------------------------------------
  // Careers
  // ----------------------------------------------------------

  const careers =
    Array.isArray(raw?.careers)
      ? raw.careers
      : [];


  // ----------------------------------------------------------
  // Rationale
  // ----------------------------------------------------------

  const rationale =
    Array.isArray(raw?.rationale)
      ? raw.rationale
      : raw?.description
        ? [raw.description]
        : [
            "This pathway was generated based on the student's profile.",
          ];


  // ----------------------------------------------------------
  // Assumptions
  // ----------------------------------------------------------

  const assumptions =
    Array.isArray(raw?.assumptions)
      ? raw.assumptions
      : [];


  // ----------------------------------------------------------
  // Uncertainty
  // ----------------------------------------------------------

  const uncertainty =
    Array.isArray(raw?.uncertainty)
      ? raw.uncertainty
      : [];


  return {
    id:
      raw?.id ??
      `pathway-${Math.random()
        .toString(36)
        .slice(2, 10)}`,

    title:
      raw?.title ??
      "AI-generated education pathway",

    route:
      raw?.route ??
      raw?.description ??
      "Education pathway generated by Groq.",

    countries,

    durationYears,

    estimatedCost:
      raw?.estimatedCost ??
      raw?.cost_range ??
      "Planning estimate; verify with institutions",

    admission,

    careers,

    fit,

    rationale,

    assumptions,

    uncertainty,
  };
}


// ============================================================
// DECISION MATRIX FALLBACK
// ============================================================

function buildDecisionMatrix(
  pathways: Pathway[]
): DecisionMatrix {
  return {
    criteria: [
      "Academic fit",
      "Budget fit",
      "Geographic flexibility",
      "Career breadth",
    ],

    rows: pathways.map(
      (pathway) => ({
        pathway: pathway.title,

        values: {
          "Academic fit":
            `${pathway.fit}/100`,

          "Budget fit":
            pathway.estimatedCost ||
            "Needs verification",

          "Geographic flexibility":
            pathway.countries.length > 1
              ? "Multiple countries"
              : "Limited",

          "Career breadth":
            pathway.careers.length >= 3
              ? "Broad"
              : "Moderate",
        },
      })
    ),
  };
}


// ============================================================
// GENERATE PATHWAYS USING GROQ
// ============================================================

export async function generatePathways(
  profile: StudentProfile
) {
  const backendProfile =
    toBackendProfile(profile);


  console.log(
    "Sending student profile to Groq backend:",
    backendProfile
  );


  let response: Response;

  try {
    response = await fetch(
      `${API_BASE}/api/pathways`,
      {
        method: "POST",

        headers: {
          "Content-Type":
            "application/json",
        },

        body: JSON.stringify(
          backendProfile
        ),
      }
    );
  } catch (error) {
    console.error(
      "Cannot connect to backend:",
      error
    );

    throw new Error(
      "Cannot connect to the AI backend. Make sure FastAPI is running on http://localhost:8000."
    );
  }


  // ----------------------------------------------------------
  // Read JSON response
  // ----------------------------------------------------------

  let data: any;

  try {
    data = await response.json();
  } catch {
    throw new Error(
      `Backend returned an invalid response (${response.status}).`
    );
  }


  // ----------------------------------------------------------
  // Backend/Groq error
  // ----------------------------------------------------------

  if (!response.ok) {
    console.error(
      "Backend error:",
      data
    );

    throw new Error(
      data?.detail ??
      `AI pathway generation failed (${response.status}).`
    );
  }


  // ----------------------------------------------------------
  // Validate pathways
  // ----------------------------------------------------------

  if (
    !data ||
    !Array.isArray(data.pathways)
  ) {
    console.error(
      "Unexpected AI response:",
      data
    );

    throw new Error(
      "Groq returned an unexpected pathway response."
    );
  }


  // ----------------------------------------------------------
  // Normalize AI pathways
  // ----------------------------------------------------------

  const pathways: Pathway[] =
    data.pathways.map(
      normalizePathway
    );


  // ----------------------------------------------------------
  // Decision matrix
  // ----------------------------------------------------------

  const matrix: DecisionMatrix =
    data.matrix ??
    buildDecisionMatrix(
      pathways
    );


  // ----------------------------------------------------------
  // Assumptions
  // ----------------------------------------------------------

  const assumptions =
    Array.isArray(
      data.assumptions
    )
      ? data.assumptions
      : [];


  console.log(
    "Groq generated pathways:",
    pathways
  );


  return {
    pathways,

    matrix,

    assumptions,
  };
}


// ============================================================
// WHAT-IF SCENARIO
// ============================================================

export async function simulateScenario(
  profile: StudentProfile,
  scenario: string
) {
  const backendProfile =
    toBackendProfile(profile);


  if (!scenario.trim()) {
    throw new Error(
      "Please enter a what-if scenario."
    );
  }


  console.log(
    "Sending scenario to Groq:",
    scenario
  );


  let response: Response;

  try {
    response = await fetch(
      `${API_BASE}/api/scenarios`,
      {
        method: "POST",

        headers: {
          "Content-Type":
            "application/json",
        },

        body: JSON.stringify({
          profile:
            backendProfile,

          scenario:
            scenario.trim(),
        }),
      }
    );
  } catch (error) {
    console.error(
      "Scenario backend connection error:",
      error
    );

    throw new Error(
      "Cannot connect to the AI backend."
    );
  }


  let data: any;

  try {
    data = await response.json();
  } catch {
    throw new Error(
      `Backend returned an invalid scenario response (${response.status}).`
    );
  }


  if (!response.ok) {
    console.error(
      "Scenario API error:",
      data
    );

    throw new Error(
      data?.detail ??
      `Scenario simulation failed (${response.status}).`
    );
  }


  console.log(
    "Groq scenario response:",
    data
  );


  return data;
}